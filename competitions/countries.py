# Accept the code ("THA"), the name ("Thailand") or a common other spelling; always store the name.
_ALIASES = {'usa': 'USA', 'united states of america': 'USA', 'uk': 'GBR', 'united kingdom': 'GBR',
            'south korea': 'KOR', 'korea': 'KOR', 'turkey': 'TUR', 'czech republic': 'CZE',
            'ivory coast': 'CIV', 'hong kong': 'HKG', 'macau': 'MAC', 'taiwan': 'TPE', 'viet nam': 'VIE'}
_BY_NAME = {name.lower(): code for code, name in PARALYMPIC_COUNTRIES.items()}


def official_country(value):
    """Return the official name for a code or name, or None if it is not a Paralympic delegation."""
    v = str(value or '').strip()
    code = v.upper() if v.upper() in PARALYMPIC_COUNTRIES else _BY_NAME.get(v.lower()) or _ALIASES.get(v.lower())
    return PARALYMPIC_COUNTRIES.get(code)
